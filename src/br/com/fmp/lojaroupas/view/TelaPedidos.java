    private void loadComboBoxFornecedores() {
        FornecedorDAO dao = new FornecedorDAO();
        List<Fornecedor> fornecedores = dao.read(); 
  
        cmbFornecedor.removeAllItems(); 
        
        for (Fornecedor f : fornecedores) {
        
            cmbFornecedor.addItem(f); 
        }
    }
  
    private void loadComboBoxStatus() {
        cmbStatus.removeAllItems();
        cmbStatus.setModel(new DefaultComboBoxModel<>(new String[] {
            "Pendente",
            "Completo",
            "Cancelado"
        }));
    }


    public void readJTable() {
        DefaultTableModel modelo = (DefaultTableModel) tblPedidos.getModel();
        modelo.setNumRows(0); 

        PedidoDAO dao = new PedidoDAO(); 
        List<Pedido> pedidos = dao.read(); 

        for (Pedido p : pedidos) { 
            modelo.addRow(new Object[]{ 
                p.getId(),
                p.getFornecedor().getNome(), 
                p.getDataPedido(),
                p.getStatus(),
                p.getValorTotal()
            });
        }
    }

