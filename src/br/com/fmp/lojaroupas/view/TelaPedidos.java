    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed

    if (txtValorTotal.getText().trim().isEmpty()) { 
        JOptionPane.showMessageDialog(null, "O campo 'Valor Total' não pode estar vazio.");
        return;
    }
    
    Pedido p = new Pedido(); 
   
    p.setFornecedor((Fornecedor) cmbFornecedor.getSelectedItem()); 
    p.setStatus((String) cmbStatus.getSelectedItem());
    p.setValorTotal(Double.parseDouble(txtValorTotal.getText()));
    p.setDataPedido(new Date());
    
    PedidoDAO dao = new PedidoDAO(); 
    dao.create(p); 

    txtValorTotal.setText("");
   
    readJTable();
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // 1. Verifica se o usuário realmente selecionou uma linha
    if (tblPedidos.getSelectedRow() == -1) { 
        JOptionPane.showMessageDialog(null, "Selecione um pedido para atualizar.");
        return;
    }
    
    // 2. Validação
    if (txtValorTotal.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "O campo 'Valor Total' não pode estar vazio.");
        return; 
    }

    // 3. Cria o objeto Pedido
    Pedido p = new Pedido(); 
    
    // 4. Pega o ID da tabela (para o UPDATE saber QUAL linha mudar)
    p.setId((int) tblPedidos.getValueAt(tblPedidos.getSelectedRow(), 0));
    
    // 5. Pega os dados atualizados dos campos
    p.setFornecedor((Fornecedor) cmbFornecedor.getSelectedItem()); 
    p.setStatus((String) cmbStatus.getSelectedItem());
    p.setValorTotal(Double.parseDouble(txtValorTotal.getText()));
    
    // 6. Pega a DATA da tabela (para não alterar a data original)
    p.setDataPedido((Date) tblPedidos.getValueAt(tblPedidos.getSelectedRow(), 2));

    // 7. Chama o DAO de ATUALIZAÇÃO (UPDATE)
    PedidoDAO dao = new PedidoDAO(); 
    dao.update(p); 

    // 8. Limpa os campos
    txtValorTotal.setText("");

    // 9. Atualiza a tabela
    readJTable();
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
       // 1. Verifica se selecionou uma linha
    if (tblPedidos.getSelectedRow() == -1) {
        JOptionPane.showMessageDialog(null, "Selecione um pedido para excluir.");
        return;
    }

    int id = (int) tblPedidos.getValueAt(tblPedidos.getSelectedRow(), 0);

    PedidoDAO dao = new PedidoDAO();
    dao.delete(id); 
    
    txtValorTotal.setText("");
    cmbFornecedor.setSelectedIndex(0);
    cmbStatus.setSelectedIndex(0);

    readJTable();
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tblPedidosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPedidosMouseClicked

    if (tblPedidos.getSelectedRow() != -1) { 
      
        String nomeFornecedor = tblPedidos.getValueAt(tblPedidos.getSelectedRow(), 1).toString();
 
        for (int i = 0; i < cmbFornecedor.getItemCount(); i++) {
            Fornecedor f = (Fornecedor) cmbFornecedor.getItemAt(i);
            if (f.getNome().equals(nomeFornecedor)) {
                cmbFornecedor.setSelectedIndex(i);
                break;
            }
        }
        
        String status = tblPedidos.getValueAt(tblPedidos.getSelectedRow(), 3).toString();
        // Loop para achar o STATUS no ComboBox
        for (int i = 0; i < cmbStatus.getItemCount(); i++) {
            String s = (String) cmbStatus.getItemAt(i);
            if (s.equals(status)) {
                cmbStatus.setSelectedIndex(i);
                break;
            }
        }
        txtValorTotal.setText(tblPedidos.getValueAt(tblPedidos.getSelectedRow(), 4).toString());
    }
    }//GEN-LAST:event_tblPedidosMouseClicked

